const createImage = ({ fallback, width, height, variants }) => ({
  fallback,
  width,
  height,
  sources: Object.fromEntries(
    Object.entries(variants).map(([name, formats]) => [
      name,
      Object.fromEntries(
        Object.entries(formats).map(([format, entries]) => [format, srcSet(entries)]),
      ),
    ]),
  ),
});

